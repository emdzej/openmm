#!/usr/bin/env python3
"""Generates, at build time, the port's index of the original's routines (into the build tree):
  routines.h   a declaration for every routine of tools/ghidra/names.tsv, `void Name(void); /* seg:off */`
               (all routines take and return the registers in R, src/cpu.h)
  routines.c   the table of every routine by address (src/fntab.h: the checker and the interrupt vectors
               look routines up by the address the original uses), and for each routine not yet ported
               a stand-in that logs PENDING_NOTE once
A routine is ported when a file under src/game/ defines it: a line `void Name(void)` with its citation
`/* Name seg:off */` on one of the three lines above.
  tools/gen_routines.py <names.tsv> <src/game> <out-dir>"""
import os
import re
import sys


def main(argv):
    names_tsv, game_dir, out = argv[1:4]
    rows = []
    for line in open(names_tsv):
        if line.startswith('#') or not line.strip():
            continue
        f = line.rstrip('\n').split('\t')
        seg, off = (int(x, 16) for x in f[0].split(':'))
        rows.append((seg, off, f[1]))
    defined = {}
    cite = re.compile(r'/\*\s*(\w+)\s+([0-9a-fA-F]{4}):([0-9a-fA-F]{4})')
    for root, _, files in os.walk(game_dir):
        for fn in sorted(files):
            if not fn.endswith('.c'):
                continue
            lines = open(os.path.join(root, fn)).read().split('\n')
            for i, l in enumerate(lines):
                m = re.match(r'void (\w+)\(void\)\s*$', l)
                if not m:
                    continue
                for j in range(max(0, i - 3), i):
                    c = cite.search(lines[j])
                    if c and c.group(1) == m.group(1):
                        defined[m.group(1)] = (int(c.group(2), 16), int(c.group(3), 16))
    by_name = {n: (s, o) for s, o, n in rows}
    for n, a in defined.items():
        if n not in by_name:
            sys.exit('gen_routines: %s is defined in src/game but not in names.tsv' % n)
        if by_name[n] != a:
            sys.exit('gen_routines: %s cited at %04x:%04x, names.tsv has %04x:%04x' % (n, *a, *by_name[n]))
    os.makedirs(out, exist_ok=True)
    h = ['/* Generated by tools/gen_routines.py from tools/ghidra/names.tsv: do not edit. */', '#pragma once', '']
    for s, o, n in rows:
        h.append('void %s(void); /* %04x:%04x */' % (n, s, o))
    c = ['/* Generated by tools/gen_routines.py: do not edit. */', '#include "fntab.h"', '#include "pending.h"',
         '#include "routines.h"', '']
    for s, o, n in rows:
        if n not in defined:
            c.append('void %s(void) { PENDING_NOTE(0x%04x%04xu, "%s"); }' % (n, s, o, n))
    c += ['', 'const FnEntry g_fntab[] = {']
    for s, o, n in sorted(rows):
        c.append('    {0x%04x%04xu, "%s", %s, %d},' % (s, o, n, n, 1 if n in defined else 0))
    c += ['};', 'const int g_fntab_n = %d;' % len(rows), '']
    for path, text in ((os.path.join(out, 'routines.h'), h), (os.path.join(out, 'routines.c'), c)):
        body = '\n'.join(text) + '\n'
        if not os.path.exists(path) or open(path).read() != body:
            open(path, 'w').write(body)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))

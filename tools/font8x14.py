#!/usr/bin/env python3
"""Generates src/font8x14.c: the 8 x 14 character cells the port's BIOS draws text with in the 350-line
graphics mode (int 10h 1301h, which FONT.BIN, the code card, writes its questions with). Not IBM's ROM
font: the glyphs come from the X11 "misc-fixed" 7x14 font by Markus Kuhn and the X Consortium, which is
in the public domain ("Public domain font. Share and enjoy."), mapped from code page 437 through Unicode.
Each 7-pixel glyph sits at the left of the 8-pixel cell; box-drawing and block glyphs repeat their
seventh column into the eighth, as the VGA repeats a line-graphics column, so lines join across cells.
  curl -O https://gitlab.freedesktop.org/xorg/font/misc-misc/-/raw/master/7x14.bdf
  tools/font8x14.py 7x14.bdf > src/font8x14.c"""
import sys

# code page 437's pictures for 01h-1Fh and 7Fh (the BIOS draws them as glyphs); 80h-FFh from Python's codec
LOW = ('\u0000☺☻♥♦♣♠•◘○◙♂♀♪♫☼'
       '►◄↕‼¶§▬↨↑↓→←∟↔▲▼')


def cp437(c):
    if c < 0x20:
        return ord(LOW[c])
    if c == 0x7f:
        return 0x2302
    return ord(bytes([c]).decode('cp437'))


def read_bdf(path):
    glyphs, cur, bits = {}, None, None
    for line in open(path, encoding='latin-1'):
        w = line.split()
        if not w:
            continue
        if w[0] == 'ENCODING':
            cur = {'enc': int(w[1])}
        elif w[0] == 'BBX' and cur is not None:
            cur['bbx'] = tuple(int(x) for x in w[1:5])
        elif w[0] == 'BITMAP' and cur is not None:
            bits = []
        elif w[0] == 'ENDCHAR' and cur is not None:
            cur['bits'] = bits
            glyphs[cur['enc']] = cur
            cur, bits = None, None
        elif bits is not None:
            bits.append(int(w[0], 16))
    return glyphs


def cell(g):
    """14 rows of 8 pixels, bit 7 the leftmost: the font's ascent is 12, its descent 2."""
    rows = [0] * 14
    if g is None:
        return rows
    w, h, xo, yo = g['bbx']
    nbytes = (w + 7) // 8
    for i, b in enumerate(g['bits']):
        y = yo + h - 1 - i               # pixel row above the baseline
        r = 11 - y
        if 0 <= r < 14:
            v = b << (8 * (1 - nbytes)) if nbytes <= 1 else b >> (8 * (nbytes - 1))
            rows[r] = (v >> xo if xo >= 0 else v << -xo) & 0xff
    return rows


def main(argv):
    glyphs = read_bdf(argv[1])
    out = ['/* Generated by tools/font8x14.py: do not edit. The 8 x 14 text cells of the port\'s BIOS (code',
           '   page 437), from the public-domain X11 misc-fixed 7x14 font (Markus Kuhn, the X Consortium):',
           '   "Public domain font. Share and enjoy." Not IBM\'s ROM font. Row 0 is the top; bit 7 the left. */',
           '#include "font8x14.h"', '', 'const uint8_t g_font8x14[256][14] = {']
    for c in range(256):
        u = cp437(c)
        g = glyphs.get(u) if c else None
        rows = cell(g)
        if 0x2500 <= u <= 0x259f:        # line graphics: the seventh column into the eighth
            rows = [r | (r & 2) >> 1 for r in rows]
        out.append('    {%s}, /* %02x */' % (', '.join('0x%02x' % r for r in rows), c))
    out.append('};')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
